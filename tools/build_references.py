# 組裝
# ---------------------------------------------------------------------------

LEGEND = """## 驗證圖例

來源欄末尾的粗體標籤只有三種：

- **本 repo 內有落地實作** — 這條來源借來的做法，在本 repo 內有對應的檔案可以讀、可以跑；
  對應位置就寫在同一列的「落地位置」欄。
- **僅引用** — 本 repo 只有摘要或連結，沒有對應實作；原始判斷留在作者的私有記憶庫，未公開。
- **已上網核對（YYYY-MM-DD）** — 該日親自抓取原頁，核對題名、授權與版本。星數、版本號這類會變的欄位
  只是當日快照，以原頁為準；標「待核對」的就是還沒查到，不補造。

沒有 URL 的地方就是找不到。「刻意不採用什麼」欄跟「借了什麼概念」欄一樣重要——
這頁一半的價值在於記下哪些東西看起來該裝、但本 vault 決定不裝，以及為什麼。
"""


def build(source_text: str, date: str, spec: dict) -> str:
    text = drop_frontmatter(source_text)
    text = strip_private_blocks(text, spec["private_block_expect"])

    # 只對作者自己有意義（或直接指向私有頁）的章節，整節刪；哪幾節由規則檔決定
    for heading_prefix, level in spec["drop_sections"]:
        text = drop_section(text, heading_prefix, level=level)

    text = rebuild_e_section(text, spec["e_heading"])
    text = apply_rules(text, build_rules(spec["text_rules"]))
    text = rewrite_tables(text, spec["label_rewrites_expect"], spec["e_rows_min"])
    text = normalise_e_status(text, spec["verified_on"])

    # 標題後面插入圖例節
    title = "# References — 方法論與工具的外部來源"
    if title not in text:
        raise BuildError("找不到主標題")
    lines = text.split("\n")
    anchor = lines.index("## 怎麼讀這頁")
    lines = lines[:anchor] + LEGEND.split("\n") + [""] + lines[anchor:]
    text = "\n".join(lines)

    body = HEADER_FMT.format(date=date) + "\n\n" + text.lstrip("\n")
    body = re.sub(r"\n{3,}", "\n\n", body)
    if not body.endswith("\n"):
        body += "\n"
    return body


# ---------------------------------------------------------------------------
# 檢查
# ---------------------------------------------------------------------------

def check_public_file(text: str, label: str) -> list:
    findings = []
    lines = text.split("\n")
    if not lines or not HEADER_RE.match(lines[0]):
        findings.append(f"ERROR {label}:1 第一行不是生成標頭"
                        "（`<!-- generated by tools/build_references.py on YYYY-MM-DD; do not edit -->`）")
    for name, pattern in ASSERT_ABSENT:
        regex = re.compile(pattern)
        for line_no, line in enumerate(lines, 1):
            if regex.search(line):
                findings.append(f"ERROR {label}:{line_no} assert_absent 命中：{name}")
                break
    return findings


def header_date(text: str) -> str | None:
    first = text.split("\n", 1)[0]
    match = HEADER_RE.match(first)
    return match.group(1) if match else None


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        prog="build_references.py",
        description="從私有母本生成公開版 docs/REFERENCES.md（公開版不手改）。",
    )
    parser.add_argument("--source", help="私有參考文獻母本（references.md）")
    parser.add_argument("--rules", help="私有規則檔（匯出 SPEC 的 Python 模組）；"
                                        "只要給了 --source 就必須給")
    parser.add_argument("--out", default=str(DEFAULT_OUT),
                        help=f"輸出路徑（預設 {DEFAULT_OUT}）")
    parser.add_argument("--check", action="store_true",
                        help="不寫檔；有 --source 就重生成比對，沒有就只驗公開檔本身")
    parser.add_argument("--date", help="生成日期（預設今天；--check 會沿用現有檔頭的日期）")
    args = parser.parse_args(argv)

    out_path = Path(args.out)

    if args.check:
        if not out_path.is_file():
            print(f"ERROR 找不到 {out_path}", file=sys.stderr)
            return EXIT_FINDINGS
        current = out_path.read_text(encoding="utf-8")
        findings = check_public_file(current, out_path.as_posix())
        if args.source:
            source_path = Path(args.source)
            if not source_path.is_file():
                print(f"ERROR 找不到母本：{source_path}", file=sys.stderr)
                return EXIT_CONFIG
            if not args.rules:
                print("ERROR --source 必須搭配 --rules（規則表在私有側，不在本 repo）",
                      file=sys.stderr)
                return EXIT_CONFIG
            date = args.date or header_date(current) or _dt.date.today().isoformat()
            try:
                spec = load_spec(Path(args.rules))
                rebuilt = build(source_path.read_text(encoding="utf-8"), date, spec)
            except BuildError as exc:
                print(f"ERROR 依母本重生成失敗：{exc}", file=sys.stderr)
                return EXIT_FINDINGS
            if rebuilt != current:
                findings.append(
                    f"ERROR {out_path.as_posix()} 與母本重生成的結果不一致"
                    "（公開版被手改了，或母本改了但沒重跑這支工具）")
        if findings:
            for line in findings:
                print(line)
            print(f"\n{len(findings)} error(s)")
            return EXIT_FINDINGS
        mode = "重生成比對" if args.source else "公開檔自檢（無母本）"
        print(f"OK 0 error(s)；{out_path.as_posix()} 通過{mode}。")
        return EXIT_OK

    if not args.source:
        print("ERROR 生成模式必須給 --source", file=sys.stderr)
        return EXIT_CONFIG
    if not args.rules:
        print("ERROR 生成模式必須給 --rules（規則表在私有側，不在本 repo）", file=sys.stderr)
        return EXIT_CONFIG
    source_path = Path(args.source)
    if not source_path.is_file():
        print(f"ERROR 找不到母本：{source_path}", file=sys.stderr)
        return EXIT_CONFIG
    date = args.date or _dt.date.today().isoformat()
    try:
        spec = load_spec(Path(args.rules))
        result = build(source_path.read_text(encoding="utf-8"), date, spec)
    except BuildError as exc:
        print(f"ERROR {exc}", file=sys.stderr)
        return EXIT_FINDINGS

    findings = check_public_file(result, out_path.as_posix())
    if findings:
        for line in findings:
            print(line)
        print(f"\n{len(findings)} error(s)；沒有寫出任何東西。")
        return EXIT_FINDINGS

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(result, encoding="utf-8")
    print(f"OK 0 error(s)；已寫出 {out_path.as_posix()}（{len(result.splitlines())} 行）。")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
